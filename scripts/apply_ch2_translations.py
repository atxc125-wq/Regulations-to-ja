# UIDs of the main Chapter 2 definitions (indices 43 to 137 in structured.json)
MAIN_CH2_RANGE = (43, 138)  # exclusive end


def apply_translations(reg: str, version: str) -> None:
    path = DATA_DIR / reg / version / "structured.json"
    with open(path, encoding="utf-8") as f:
        data = json.load(f)

    paras = data["paragraphs"]
    updated = 0

    # Apply translations to main Chapter 2 paragraphs only
    for p in paras[MAIN_CH2_RANGE[0]:MAIN_CH2_RANGE[1]]:
        if p.get("type", "paragraph") != "paragraph":
            continue
        num = p.get("number", "")
        if num in TRANSLATIONS:
            t = TRANSLATIONS[num]
            p["translation"] = t["translation"]
            p["summary_ja"] = t["summary_ja"]
            p["title_ja"] = t["title_ja"]
            p["status"] = "translated"
            updated += 1
            print(f"  [{num}] {t['title_ja']}")

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"\n✓ {updated} paragraphs translated. Saved → {path}")


if __name__ == "__main__":
    apply_translations("R13", "Rev9")
